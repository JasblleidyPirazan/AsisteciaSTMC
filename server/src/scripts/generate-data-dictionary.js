#!/usr/bin/env node
/**
 * Regenerates `docs/database-dictionary.md` from `services/dataDictionary.js`.
 *
 *   cd server && npm run docs:dictionary
 *
 * The markdown is a build output: never edit it by hand — edit the dictionary
 * module (which the export button also reads) and run this script again.
 */

const fs = require('fs');
const path = require('path');
const { TABLES, ENUMS } = require('../services/dataDictionary');

const OUT = path.join(__dirname, '../../../docs/database-dictionary.md');

// GitHub conserva los guiones bajos al generar el ancla de un encabezado.
const anchor = (t) => `#${t}`;
const esc = (s) => String(s || '').replace(/\|/g, '\\|');

// Diagrama ER derivado de las claves foráneas declaradas en el diccionario
// ("FK → tabla.columna"), así no puede desincronizarse de las columnas.
function erDiagram() {
  const edges = [];
  for (const t of TABLES) {
    for (const c of t.columns) {
      const m = /FK → (\w+)\./.exec(c.key || '');
      if (!m) continue;
      const optional = c.nullable ? 'o' : '|';
      edges.push(`    ${m[1]} |${optional}--o{ ${t.table} : "${c.column}"`);
    }
  }
  return ['```mermaid', 'erDiagram', ...edges, '```'].join('\n');
}

function tableSection(t) {
  const lines = [];
  lines.push(`### \`${t.table}\``);
  lines.push('');
  lines.push(
    `*Prisma model:* \`${t.model}\` · *area:* ${t.group} · *columns:* ${t.columns.length}` +
      (t.legacy ? ' · **legacy — kept for historical rows only**' : '')
  );
  lines.push('');
  lines.push(t.description);
  lines.push('');
  lines.push('| Column | Type | Null | Key | Description |');
  lines.push('|---|---|---|---|---|');
  for (const c of t.columns) {
    lines.push(
      `| \`${c.column}\` | ${c.type} | ${c.nullable ? 'yes' : 'no'} | ${esc(c.key || '')} | ${esc(c.description)}${
        c.sensitive ? ' **Redacted in exports.**' : ''
      } |`
    );
  }
  lines.push('');
  const keys = [];
  if (t.keys?.primary?.length) keys.push(`**PK:** (${t.keys.primary.join(', ')})`);
  for (const u of t.keys?.unique || []) keys.push(`**Unique:** (${u.join(', ')})`);
  for (const i of t.keys?.indexes || []) keys.push(`**Index:** (${i.join(', ')})`);
  if (keys.length) {
    lines.push(keys.join(' · '));
    lines.push('');
  }
  if (t.relations?.length) {
    lines.push('**Relations**');
    lines.push('');
    for (const [field, target, desc] of t.relations) {
      lines.push(`- \`${field}\` → \`${target}\`${desc ? ` — ${desc}` : ''}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function build() {
  const groups = [...new Set(TABLES.map((t) => t.group))];
  const out = [];

  out.push('# Database Dictionary — AsisteciaSTMC');
  out.push('');
  out.push(
    '> **Generated file — do not edit by hand.** It is produced from `server/src/services/dataDictionary.js` by ' +
      '`cd server && npm run docs:dictionary`. The same module feeds the *Data Dictionary* sheet of the full ' +
      'database export, so the document and the exported workbook always describe the same schema. A unit test ' +
      '(`tests/unit/dataDictionary.test.js`) fails if `schema.prisma` gains, renames or drops anything that is not ' +
      'documented here.'
  );
  out.push('');
  out.push(
    `**Engine:** PostgreSQL (Prisma ORM v5, versioned migrations) · **Tables:** ${TABLES.length} · ` +
      `**Enums:** ${ENUMS.length} · **Columns:** ${TABLES.reduce((s, t) => s + t.columns.length, 0)}`
  );
  out.push('');

  out.push('## Conventions');
  out.push('');
  out.push(
    [
      '- **Names.** Prisma models are `PascalCase`, physical tables and columns are `snake_case` (the `@@map` / `@map` of the schema). This document lists the *physical* names — what you see in SQL and in the export.',
      '- **Primary keys.** Every entity uses a `cuid` text id generated by the application, never a database sequence. Join tables use a composite key of the two foreign keys.',
      '- **Soft delete.** Rows are not deleted: `active = false` plus `deactivation_reason` / `deactivated_at`. Hard deletes exist only behind explicit admin actions.',
      '- **Dates.** `date` columns are calendar days in America/Bogota (no time zone attached); `timestamp` columns are instants stored in UTC.',
      '- **Money.** All amounts are Colombian pesos (COP) in `numeric(12,2)`.',
      '- **Fortnights.** Payroll periods are text: `"YYYY-MM-1"` (days 1–15) and `"YYYY-MM-2"` (16 to end of month).',
      '- **Derived state.** Student status (trial / pre-enrolled / enrolled / fully paid / suspended / inactive) and attendance statistics are computed on the server from payments, attendance and rates. They are not stored — do not look for a status column.',
    ].join('\n')
  );
  out.push('');

  out.push('## Table index');
  out.push('');
  for (const g of groups) {
    out.push(`**${g}**`);
    out.push('');
    out.push('| Table | Model | Purpose |');
    out.push('|---|---|---|');
    for (const t of TABLES.filter((x) => x.group === g)) {
      const purpose = esc(t.description.split('. ')[0]) + (t.legacy ? ' *(legacy)*' : '');
      out.push(`| [\`${t.table}\`](${anchor(t.table)}) | \`${t.model}\` | ${purpose}. |`);
    }
    out.push('');
  }

  out.push('## Relationships');
  out.push('');
  out.push('Foreign keys declared in the schema (crow’s foot points at the many side).');
  out.push('');
  out.push(erDiagram());
  out.push('');

  for (const g of groups) {
    out.push(`## ${g}`);
    out.push('');
    for (const t of TABLES.filter((x) => x.group === g)) out.push(tableSection(t));
  }

  out.push('## Enums');
  out.push('');
  for (const e of ENUMS) {
    out.push(`### \`${e.name}\``);
    out.push('');
    out.push(e.description);
    out.push('');
    out.push('| Value | Meaning |');
    out.push('|---|---|');
    for (const [v, d] of e.values) out.push(`| \`${v}\` | ${esc(d)} |`);
    out.push('');
  }

  out.push('## Exporting the data');
  out.push('');
  out.push(
    [
      'An ADMIN or SUPERADMIN can download the whole database from **Configuración → Base de datos**:',
      '',
      '- **Excel** (`GET /api/system/export/database?format=xlsx`) — one sheet per table plus an *Overview* sheet with the row counts, this dictionary as a *Data Dictionary* sheet and an *Enums* sheet.',
      '- **JSON** (`GET /api/system/export/database?format=json`) — the same content as a logical backup, keyed by physical table name.',
      '',
      'Columns marked as sensitive (today only `users.password_hash`) are replaced by `[REDACTED]` in both formats: password hashes never leave the server. The export is a *data* dump, not a `pg_dump`; to restore a server, take a PostgreSQL backup instead.',
    ].join('\n')
  );
  out.push('');

  return out.join('\n');
}

const md = build();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md, 'utf8');
console.log(`Diccionario escrito en ${path.relative(process.cwd(), OUT)} (${md.split('\n').length} líneas)`);
